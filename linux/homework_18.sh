#!/bin/bash

# Запрос адреса у пользователя, если он не передан аргументом
if [ -z "$1" ]; then
    read -p "Введите IP-адрес или домен для пинга: " TARGET
else
    TARGET="$1"
fi

# Проверка, что цель не пустая
if [ -z "$TARGET" ]; then
    echo "Ошибка: Адрес не указан."
    exit 1
fi

echo "Начинаем бесконечный пинг для $TARGET (интервал 1 сек)..."
echo "Критерии: отклик > 100 мс или 3 потери подряд."
echo "Для остановки нажмите Ctrl+C"
echo "--------------------------------------------------"

# Счетчик последовательных неудачных попыток
failed_count=0

while true; do
    # Выполняем один пинг с таймаутом в 1 секунду. 
    # Вытаскиваем время отклика (time=...) из вывода.
    ping_result=$(ping -c 1 -W 1 "$TARGET" 2>/dev/null)
    
    # Проверяем код возврата команды ping
    if [ $? -ne 0 ]; then
        # Пинг не прошел (таймаут или узел недоступен)
        ((failed_count++))
        
        if [ "$failed_count" -ge 3 ]; then
            echo "[ВНИМАНИЕ] Не удалось выполнить пинг в течение $failed_count последовательных отправок пакетов!"
        fi
    else
        # Пинг успешен, сбрасываем счетчик потерь
        failed_count=0
        
        # Извлекаем время в миллисекундах и округляем до целого числа для сравнения
        ping_time=$(echo "$ping_result" | grep -oE "time=[0-9.]+" | cut -d= -f2)
        
        if [ -n "$ping_time" ]; then
            # Округляем плавающую точку до целого числа (например, 12.3 -> 12)
            ping_time_int=$(printf "%.0f" "$ping_time")
            
            # Проверяем превышение порога в 100 мс
            if [ "$ping_time_int" -gt 100 ]; then
                echo "[ПРЕДУПРЕЖДЕНИЕ] Время пинга превысило 100 мс! Текущее: ${ping_time} мс"
            fi
        fi
    fi

    # Интервал между попытками — 1 секунда
    sleep 1
done
